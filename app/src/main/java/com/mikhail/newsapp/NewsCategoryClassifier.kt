package com.mikhail.newsapp

/**
 * Локальный классификатор новостей по категориям.
 *
 * Работает только с заголовком, описанием и (опционально) именем сайта —
 * без сетевых запросов, внешних API и ML-моделей.
 *
 * Принцип работы:
 * 1. Текст токенизируется по словам (деление по неподSymbol-символам).
 * 2. Каждая категория набирает очки за совпадения ключевых слов:
 *    - точное совпадение слова с ключевым словом;
 *    - для ключевых слов длиной >= 5: токен начинается с ключевого слова, и
 *      следующий символ — русская гласная (склонение: технолог**и**и, программ**м**и).
 *    Это protects от ложных срабатываний: "код" (длина 3) не сработает на
 *    "кодекс", так как короткие ключевые слова matching только по точному слову.
 * 3. Заголовок весит больше описания (3 vs 1 очка).
 * 4. Имя сайта/источника используется только как дополнительный сигнал (+1 очко)
 *    — никогда не является безусловным основанием.
 * 5. Победитель — категория с максимальным количеством очков. При равенстве
 *    побеждает та, что объявлена раньше в [keywords] (порядок задаёт приоритет).
 * 6. Если ни одна категория не набрала очков — возвращается [NewsCategory.OTHER].
 *
 * Исходные заголовок и описание не изменяются. Результат детерминирован.
 */
