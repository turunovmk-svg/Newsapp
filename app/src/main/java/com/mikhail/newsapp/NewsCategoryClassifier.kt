    /** Слова-искключения: при наличии в тексте категория не назначается даже при совпадении ключевых слов. */
    private val exclusionWords = mapOf(
        NewsCategory.TECH to setOf("кодекс", "кодировк"),
        NewsCategory.WORLD to setOf("мирный")
    )

    private val russianVowels = setOf('а', 'е', 'ё', 'и', 'о', 'у', 'ы', 'э', 'ю', 'я')

    private fun tokenize(text: String): List<String> {
        return text
            .lowercase()
            .split(Regex("[^а-яёa-z0-9]+"))
            .filter { it.isNotBlank() }
            .distinct()
    }

    /**
     * Проверяет, совпадает ли токен с ключевым словом.
     *
     * Для коротких слов (<= 4 символов) требуется точное совпадение — это
     * предотвращает ложные срабатывания ("код" ≠ "кодекс").
     * Для длинных слов допускается начало слова с ключевого слова + русская гласная
     * ("технологии" ≈ "технолог").
     */
    private fun tokenMatchesKeyword(token: String, kw: String): Boolean {
        if (token == kw) return true
        if (kw.length >= 5 && token.startsWith(kw) && token.length > kw.length) {
            val nextChar = token[kw.length]
            return nextChar in russianVowels
        }
        return false
    }

    /**
     * Классифицирует пост по заголовку и описанию.
     *
     * @param title заголовок статьи (обязательный)
     * @param description описание/анонс (может быть null)
     * @param sourceName имя сайта/источника — только дополнительный сигнал (+1 очко)
     * @return категория; [NewsCategory.OTHER], если признаков недостаточно
     */
    fun classify(title: String?, description: String?, sourceName: String?): NewsCategory {
        val titleTokens = tokenize(title ?: "")
        val descTokens = tokenize(description ?: "")
        val allTokens = (titleTokens + descTokens).toSet()

        var bestCategory = NewsCategory.OTHER
        var bestScore = 0

        for ((category, words) in keywords) {
            var score = 0
            for (kw in words) {
                val titleHit = titleTokens.any { tokenMatchesKeyword(it, kw) }
                val descHit = descTokens.any { tokenMatchesKeyword(it, kw) }
                if (titleHit) score += 3
                if (descHit) score += 1
            }
            // Штраф за известные ложные срабатывания
            val categoryExclusions = exclusionWords[category] ?: emptySet()
            if (categoryExclusions.any { it in allTokens }) score -= 2
            if (score > bestScore) {
                bestScore = score
                bestCategory = category
            }
            // При равном счёте побеждает категория, объявленная раньше
        }

        // Источник как Additional сигнал только при неопределённом результате
        if (bestScore == 0 && sourceName != null && sourceName.isNotBlank()) {
            val sourceLower = sourceName.lowercase()
            for ((category, words) in keywords) {
                if (words.any { kw -> sourceLower.contains(kw) }) {
                    return category
                }
            }
        }

        return if (bestScore > 0) bestCategory else NewsCategory.OTHER
    }
}
